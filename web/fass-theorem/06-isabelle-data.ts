out.push(``);
out.push(`definition ${thy.toLowerCase()}_Q :: "int list list" where\n  "${thy.toLowerCase()}_Q = ${nestedList(TYPES.map((T) => ilist((J.quadCorner['2'][T] as (number | null)[]).map((q) => (q === null ? -1 : q)))))}"`);
out.push(``);
out.push(`definition ${thy.toLowerCase()}_Q1 :: "int list list" where\n  "${thy.toLowerCase()}_Q1 = ${nestedList(TYPES.map((T) => ilist((J.quadCorner['1'][T] as (number | null)[]).map((q) => (q === null ? -1 : q)))))}"`);
out.push(``);
out.push(`definition ${thy.toLowerCase()}_linear :: "(int \\<times> int) list" where\n  "${thy.toLowerCase()}_linear = [${(J.linear as { k: number; m: number }[]).map((l) => `(${l.m ? -1 : 1},${l.k})`).join(', ')}]"`);
out.push(``);
out.push(`definition ${thy.toLowerCase()}_corners1 :: "nat list list" where\n  "${thy.toLowerCase()}_corners1 = ${nestedList(TYPES.map((T) => ilist(J.corners['1'][T])))}"`);
out.push(``);
out.push(`definition ${thy.toLowerCase()}_dir1 :: "int list list list" where\n  "${thy.toLowerCase()}_dir1 = ${nestedList(TYPES.map((T) => `[${(J.words['1'][T] as { dir: number[] }[]).map((w) => ilist(w.dir)).join(', ')}]`))}"`);
out.push(``);
// labels as (sign, major, minor) triples
const lab = (s: string): string => { const m = /^(-?)(\d+)\.(\d+)[A-Z]$/.exec(s)!; return `(${m[1] ? -1 : 1},${m[2]},${m[3]})`; };
