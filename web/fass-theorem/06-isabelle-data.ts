out.push(`  the substitution rules (child type per slot, 9 = empty), the tables B, G, CT, Q, the slot`);
out.push(`  linear parts, and the level-1 words are those of tables-${cfg.family}.json.\\<close>`);
out.push(``);
out.push(`definition ${thy.toLowerCase()}_classes :: "int list list" where\n  "${thy.toLowerCase()}_classes = ${nestedList(TYPES.map((T) => ilist(J.classes[T])))}"`);
out.push(``);
out.push(`definition ${thy.toLowerCase()}_rules :: "nat list list" where\n  "${thy.toLowerCase()}_rules = ${nestedList(TYPES.map((T) => ilist((J.rules[T] as string[]).map((c) => (c === 'null' ? 9 : idx(c))))))}"`);
out.push(``);
out.push(`definition ${thy.toLowerCase()}_B :: "(nat \\<times> nat) list list list" where\n  "${thy.toLowerCase()}_B = ${nestedList(TYPES.map((T) => `[${(J.B[T] as { s: number; e: number }[][]).map((arc) => `[${arc.map(({ s, e }) => `(${s},${e})`).join(',')}]`).join(', ')}]`))}"`);
